def _copy_text(src, dst):
    with open(src) as fh:
        text = fh.read()
    with open(dst, "w") as fh:
        fh.write(text)


def _copy_text_replace(src, dst, replacements):
    with open(src) as fh:
        text = fh.read()
    for old, new in replacements:
        text = text.replace(old, new)
    with open(dst, "w") as fh:
        fh.write(text)


