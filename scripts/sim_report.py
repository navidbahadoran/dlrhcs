def _write_csv(path, rows, fields):
    def clean(val):
        if isinstance(val, (float, np.floating)) and not np.isfinite(float(val)):
            return ""
        return val

    with open(path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fields)
        w.writeheader()
        for row in rows:
            w.writerow({key: clean(row.get(key, "")) for key in fields})


def _remove_obsolete_tex():
    removed = []
    for folder in (OUT, PAPER_TABLES):
        if not os.path.isdir(folder):
            continue
        for name in OBSOLETE_OUTPUT_TEX:
            path = os.path.join(folder, name)
            if os.path.exists(path):
                os.remove(path)
                removed.append(path)
        if folder == PAPER_TABLES:
            for path in glob(os.path.join(folder, "*.tex")):
                name = os.path.basename(path)
                if (name.startswith("tab_mc_") or name in OBSOLETE_OUTPUT_TEX) and name not in ACTIVE_MANUSCRIPT_TEX:
                    os.remove(path)
                    removed.append(path)
    return removed


def _latex_table(rows, fields, align, caption_note=None):
    lines = [r"\begin{tabular}{" + align + "}", r"\toprule"]
    lines.append(" & ".join(_latex_escape(f) for f in fields) + r" \\")
    lines.append(r"\midrule")
    for row in rows:
        vals = []
        for fkey in fields:
            val = row.get(fkey, "")
            if val is None:
                vals.append("--")
            elif isinstance(val, (float, np.floating)):
                vals.append(fmt(val))
            else:
                vals.append(_latex_escape(val))
        lines.append(" & ".join(vals) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    if caption_note:
        lines.append("% " + caption_note)
    return "\n".join(lines)


def _write_tex(path, rows, fields, align, note=None):
    with open(path, "w") as fh:
        fh.write(_latex_table(rows, fields, align, note) + "\n")


